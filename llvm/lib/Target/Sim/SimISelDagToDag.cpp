#define DEBUG_TYPE "sim-isel"

namespace {

class SimDAGToDAGISel : public SelectionDAGISel {
  const SimSubtarget *Subtarget = nullptr;

public:
  static char ID;
  SimDAGToDAGISel() = delete;
  explicit SimDAGToDAGISel(SimTargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISel(TM, OptLevel) {}

  bool runOnMachineFunction(MachineFunction &MF) override {
    Subtarget = &MF.getSubtarget<SimSubtarget>();
    return SelectionDAGISel::runOnMachineFunction(MF);
  }

  void Select(SDNode *N) override;

// Include the pieces autogenerated from the target description.
#include "SimGenDAGISel.inc"
};
class SimDAGToDAGISelLegacy : public SelectionDAGISelLegacy {
public:
  static char ID;

  SimDAGToDAGISelLegacy(SimTargetMachine &TM, CodeGenOptLevel OptLevel)
      : SelectionDAGISelLegacy(
            ID, std::make_unique<SimDAGToDAGISel>(TM, OptLevel)) {}

  StringRef getPassName() const override {
    return "Sim DAG->DAG Pattern Instruction Selection";
  }
};
} // end anonymous namespace

char SimDAGToDAGISelLegacy::ID = 0;

/// This pass converts a legalized DAG into a Sim-specific DAG, ready for
/// instruction scheduling.
FunctionPass *llvm::createSimISelDag(SimTargetMachine &TM,
                                     CodeGenOptLevel OptLevel) {
  return new SimDAGToDAGISelLegacy(TM, OptLevel);
}

void SimDAGToDAGISel::Select(SDNode *Node) {
  if (Node->isMachineOpcode()) {
    Node->setNodeId(-1);
    return;
  }
  SDLoc DL(Node);
  SelectCode(Node);
}
